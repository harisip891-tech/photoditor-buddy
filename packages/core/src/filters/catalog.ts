/**
 * Compact constructor used by the tables below. Ids are derived from category and name so
 * they stay stable (they are stored in saved projects and in the SDK API).
 */
function f(
  category: FilterCategory,
  name: string,
  preset: AdjustmentPreset,
  lut?: LutRecipe,
): FilterDefinition {
  const id = `${category}-${name}`
    .toLowerCase()
    .replace(/&/g, 'and')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');
  return lut ? { id, name, category, preset, lut } : { id, name, category, preset };
}

/** Shortcut for a split-toning block (highlight hue/sat, shadow hue/sat, balance). */
function tone(
  hh: number,
  hs: number,
  sh: number,
  ss: number,
  balance = 0,
): AdjustmentPreset['splitToning'] {
  return {
    highlightHue: hh,
    highlightSaturation: hs,
    shadowHue: sh,
    shadowSaturation: ss,
    balance,
  };
}

